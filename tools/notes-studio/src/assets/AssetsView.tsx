import { ChevronRight, FileCode, Folder, Image, MoreHorizontal, PanelRight, Pencil, Trash2, Workflow } from 'lucide-react';
import { DIAGRAM_SUFFIX } from '@site/lib/diagram/source';
import { useEffect, useRef, useState } from 'react';
import { classifyPath } from '../../server/security/asset-types';
import type { AssetAnswer, AssetInfo, AssetsClient, AssetUsage } from '../api/assets';
import { assetDirFor } from '../media/asset-names';
import { buildAssetTree, DIAGRAMS_PREFIX, foldersTo, nameOf, type AssetFolder } from './asset-tree';
import { isImage } from './asset-facts';
import { plural, said } from './asset-changes';
import { DeleteAssetDialog, RenameAssetDialog } from './AssetDialogs';
import type { useAssetList } from './useAssetList';

type Menu = { asset: AssetInfo; top: number; left: number };
type Dialog = { kind: 'rename' | 'delete'; asset: AssetInfo };


const dirOf = (path: string) => path.slice(0, path.lastIndexOf('/'));

// What the rows need from the view around them.
type View = {
  filtering: boolean;
  openFolders: ReadonlySet<string>;
  toggle: (path: string) => void;
  current: string | null;
  open: (path: string) => void;
  openMenu: (menu: Menu) => void;
};

const isDiagram = (path: string) => classifyPath(path) === 'diagram';

function FileRow({ asset, view }: { asset: AssetInfo; view: View }) {
  const name = nameOf(asset.path);
  const diagram = isDiagram(asset.path);
  // A diagram's name ends at `.diagram.json`, as <Diagram src> writes it.
  const dot = diagram ? name.length - DIAGRAM_SUFFIX.length : name.lastIndexOf('.');
  const used = asset.usages.length;
  const current = view.current === asset.path;
  return (
    <li>
      <div className="studio-tree-row" aria-current={current ? 'page' : undefined}>
        <span className="studio-tree-chevron" />
        <button type="button" className="studio-tree-label" title={asset.path} onClick={() => { view.open(asset.path); }}>
          {diagram ? <Workflow size={16} /> : isImage(name) ? <Image size={16} /> : <FileCode size={16} />}
          <span className="truncate">
            {name.slice(0, dot)}
            <span className="text-[var(--fde-muted-foreground)]">{name.slice(dot)}</span>
          </span>
        </button>
        {asset.sources.length > 0 && (
          <span className="studio-asset-uses" title={`Generated by ${asset.sources.map((source) => source.path).join(', ')}`}>
            diagram
          </span>
        )}
        <span className="studio-asset-uses" data-unused={used === 0 || undefined} title={used === 0 ? 'No note uses it' : `Used ${plural(used, 'time')}`}>
          {used === 0 ? 'unused' : `${String(used)}×`}
        </span>
        <button
          type="button"
          className="studio-tree-more"
          aria-label={`Actions for ${name}`}
          onClick={(event) => {
            const box = event.currentTarget.getBoundingClientRect();
            view.openMenu({ asset, top: box.bottom + 2, left: box.left });
          }}
        >
          <MoreHorizontal size={14} />
        </button>
      </div>
    </li>
  );
}

function FolderItems({ folder, nested = false, view }: { folder: AssetFolder; nested?: boolean; view: View }) {
  return (
    <ul role="group" className={nested ? 'studio-tree-group studio-tree-nested' : 'studio-tree-group'}>
      {folder.folders.map((child) => {
        const open = view.filtering || view.openFolders.has(child.path);
        return (
          <li key={child.path}>
            <div className="studio-tree-row">
              <button type="button" className="studio-tree-chevron" aria-expanded={open} aria-label={`${open ? 'Collapse' : 'Expand'} ${child.name}`} onClick={() => { view.toggle(child.path); }}>
                <ChevronRight size={14} data-open={open || undefined} />
              </button>
              <button type="button" className="studio-tree-label" title={child.path} onClick={() => { view.toggle(child.path); }}>
                <Folder size={16} />
                <span className="truncate">{child.name}</span>
              </button>
            </div>
            {open && <FolderItems folder={child} nested view={view} />}
          </li>
        );
      })}
      {folder.files.map((asset) => <FileRow key={asset.path} asset={asset} view={view} />)}
    </ul>
  );
}

// The sidebar's Assets view: public/notes as folders, then diagrams/, each
// file with how many times notes use it (a diagram: the <Diagram> that draw
// it; it opens the diagram editor and is not renamed or deleted here). A file opens its asset page in the main pane
// (`onOpen`; `current` is the one open there); its menu renames it (every
// reference follows) or deletes it (only once nothing uses it), and
// `onChanged` hears what changed. `active` is the open note (a worktree
// path); while it has edits not on disk yet (`unsaved`), rename and delete
// wait, since the server only sees references that are saved. `readOnly`
// (main) leaves only Open in the row menu.
export function AssetsView({ client, list, active, current, unsaved, readOnly = false, onOpen, onOpenUsage, onChanged }: {
  client: AssetsClient;
  list: ReturnType<typeof useAssetList>;
  active: string | null;
  current: string | null;
  unsaved: boolean;
  readOnly?: boolean;
  onOpen: (path: string) => void;
  onOpenUsage: (usage: AssetUsage) => void;
  onChanged: (answer: AssetAnswer) => void;
}) {
  const [query, setQuery] = useState('');
  const [unused, setUnused] = useState(false);
  const [open, setOpen] = useState<ReadonlySet<string>>(() => new Set([...(active === null ? [] : foldersTo(assetDirFor(active))), ...(current === null ? [] : foldersTo(dirOf(current)))]));
  const [menu, setMenu] = useState<Menu | null>(null);
  const [dialog, setDialog] = useState<Dialog | null>(null);
  const [status, setStatus] = useState<{ text: string; error: boolean } | null>(null);
  const [shownFor, setShownFor] = useState(active);
  const [currentFor, setCurrentFor] = useState(current);
  const menuRef = useRef<HTMLDivElement>(null);

  // The open note's asset folder shows when a note is opened.
  if (active !== shownFor) {
    setShownFor(active);
    if (active !== null) setOpen(new Set([...open, ...foldersTo(assetDirFor(active))]));
  }
  // So does the folder of the asset open in the main pane.
  if (current !== currentFor) {
    setCurrentFor(current);
    if (current !== null) setOpen(new Set([...open, ...foldersTo(dirOf(current))]));
  }

  useEffect(() => {
    if (!menu) return;
    const close = (event: Event) => {
      if (event instanceof KeyboardEvent ? event.key === 'Escape' : !menuRef.current?.contains(event.target as Node)) setMenu(null);
    };
    window.addEventListener('mousedown', close);
    window.addEventListener('keydown', close);
    menuRef.current?.querySelector<HTMLButtonElement>('button:not(:disabled)')?.focus();
    return () => {
      window.removeEventListener('mousedown', close);
      window.removeEventListener('keydown', close);
    };
  }, [menu]);

  const { assets, error, reload } = list;
  if (assets === null) {
    return error === null
      ? <p className="px-3 py-2 text-[12.5px] text-[var(--fde-muted-foreground)]">Loading assets…</p>
      : <p role="alert" className="p-3 text-[12.5px] text-[var(--fde-error)]">Could not load the assets: {error}</p>;
  }
  const tree = buildAssetTree(assets, { query, unused });
  const diagrams = buildAssetTree(assets, { query, unused, prefix: DIAGRAMS_PREFIX });
  const unusedCount = assets.filter((asset) => asset.usages.length === 0).length;
  const view: View = {
    filtering: query.trim() !== '' || unused,
    openFolders: open,
    toggle: (path) => {
      setOpen((current) => {
        const next = new Set(current);
        if (!next.delete(path)) next.add(path);
        return next;
      });
    },
    current,
    open: onOpen,
    openMenu: setMenu,
  };
  // The dialog works on the asset as listed now: its mtime and usages.
  const listed = dialog && assets.find((asset) => asset.path === dialog.asset.path);
  const done = (answer: AssetAnswer) => {
    setDialog(null);
    setStatus({ text: said(answer), error: false });
    onChanged(answer);
    reload();
  };
  const none = (folder: AssetFolder) => folder.folders.length === 0 && folder.files.length === 0;
  const empty = none(tree) && none(diagrams);

  return (
    <div className="flex min-h-0 flex-1 flex-col gap-2 p-2.5">
      <input type="search" aria-label="Filter assets" placeholder="Filter by name" className="studio-input" value={query} onChange={(event) => { setQuery(event.target.value); }} />
      <div className="studio-asset-filter" role="group" aria-label="Show">
        <button type="button" aria-pressed={!unused} onClick={() => { setUnused(false); }}>All {assets.length}</button>
        <button type="button" aria-pressed={unused} onClick={() => { setUnused(true); }}>Unused {unusedCount}</button>
      </div>
      {error !== null && <p role="alert" className="studio-tree-error">Could not reload the assets: {error}</p>}
      {empty ? (
        <p className="px-2 text-[12.5px] text-[var(--fde-muted-foreground)]">{assets.length === 0 ? 'No files in public/notes yet.' : 'No asset matches.'}</p>
      ) : (
        <div className="min-h-0 overflow-auto">
          <FolderItems folder={tree} view={view} />
          {!none(diagrams) && (
            <>
              <h3 className="studio-asset-area">Diagrams</h3>
              <FolderItems folder={diagrams} view={view} />
            </>
          )}
        </div>
      )}
      {status && (
        <p role={status.error ? 'alert' : 'status'} className={status.error ? 'studio-tree-error' : 'studio-tree-status'}>
          {status.text}
        </p>
      )}
      {menu !== null && (
        <div ref={menuRef} role="menu" className="studio-menu" style={{ top: menu.top, left: menu.left }}>
          <button type="button" role="menuitem" onClick={() => { setMenu(null); onOpen(menu.asset.path); }}>
            <PanelRight size={14} /> Open
          </button>
          {!readOnly && !isDiagram(menu.asset.path) && (
            <>
              <button type="button" role="menuitem" disabled={unsaved} onClick={() => { setMenu(null); setDialog({ kind: 'rename', asset: menu.asset }); }}>
                <Pencil size={14} /> Rename…
              </button>
              <hr />
              <button type="button" role="menuitem" className="studio-menu-danger" disabled={unsaved} onClick={() => { setMenu(null); setDialog({ kind: 'delete', asset: menu.asset }); }}>
                <Trash2 size={14} /> Delete…
              </button>
              {unsaved && <p className="studio-menu-hint">The open note has unsaved changes. Rename or delete once it shows Saved.</p>}
            </>
          )}
        </div>
      )}
      {dialog?.kind === 'rename' && listed && (
        <RenameAssetDialog client={client} asset={listed} onDone={done} onClose={() => { setDialog(null); }} />
      )}
      {dialog?.kind === 'delete' && listed && (
        <DeleteAssetDialog
          client={client}
          asset={listed}
          onDone={done}
          onClose={() => { setDialog(null); }}
          onOpenUsage={(usage) => { setDialog(null); onOpenUsage(usage); }}
        />
      )}
    </div>
  );
}
